// gen.go:TableSpec → 生成代码。全部代码片段在 Go 侧构造,模板只做机械拼接,
// 生成结果经 go/format 格式化。

// Generate 是插件入口(sqlc 经 stdin/stdout 调用)。
func Generate(_ context.Context, req *pb.GenerateRequest) (*pb.GenerateResponse, error) {
	// dump-first(§4.6):DYNQ_DUMP_REQUEST=path 时把请求 protojson 落盘后退出,
	// 用于验证 COMMENT ON 是否进入 columns[].comment、类型 oneof 真实形态、
	// enum 值列表是否完整,并作为 golden 测试的真实夹具。
	if path := os.Getenv("DYNQ_DUMP_REQUEST"); path != "" {
		out, err := protojson.MarshalOptions{Multiline: true}.Marshal(req)
		if err != nil {
			return nil, fmt.Errorf("dump request: %w", err)
		}
		if err := os.WriteFile(path, out, 0o644); err != nil {
			return nil, fmt.Errorf("dump request: %w", err)
		}
	}
	opts, err := ParseOptions(req)
	if err != nil {
		return nil, err
	}
	tables, err := buildTableSpecs(req, opts)
	if err != nil {
		return nil, err
	}
	resp := &pb.GenerateResponse{}
	for _, spec := range tables {
		src, err := renderTable(spec, opts)
		if err != nil {
			return nil, fmt.Errorf("table %s: %w", spec.Name, err)
		}
		resp.Files = append(resp.Files, &pb.File{
			Name:     spec.Name + "_dynamic_gen.go",
			Contents: src,
		})
	}
	return resp, nil
}

// ---- 生成上下文 ----

type tableCode struct {
	spec *TableSpec
	opts *Options

	modelPkg string // 模型类型限定前缀("" 同包 / "models." 跨包)
	dbtx     string // DBTX 引用
	res      string // 资源 PascalCase(如 Users)
	sing     string // 单数实体 PascalCase(如 User)
	reg      string // registry 变量名前缀(如 users)
}

func renderTable(spec *TableSpec, opts *Options) ([]byte, error) {
	tc := &tableCode{spec: spec, opts: opts}
	if opts.ModelImport != "" {
		tc.modelPkg = opts.ModelPackage + "."
	}
	tc.dbtx = "DBTX"
	if opts.ModelImport != "" {
		tc.dbtx = tc.modelPkg + "DBTX"
	}
	tc.res = goName(spec.Resource)
	tc.sing = spec.Singular
	tc.reg = lowerFirst(spec.Name)

	parseSrc := tc.parseSection()
	sections := []string{
		tc.headerSection(),
		tc.registrySection(),
		tc.fieldConstSection(),
		tc.paramsSection(),
		parseSrc,
		tc.validateSection(),
		tc.whereSection(),
		tc.cursorValuesSection(),
		tc.listSection(),
		tc.countSection(),
		tc.schemaSection(),
	}
	var b strings.Builder
	for _, s := range sections {
		b.WriteString(s)
		b.WriteString("\n")
	}
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt generated source: %w\n--- source ---\n%s", err, b.String())
	}
	return src, nil
}

func (tc *tableCode) headerSection() string {
	spec := tc.spec
	var b strings.Builder
	b.WriteString("// Code generated by sqlc_gen_dynamic. DO NOT EDIT.\n//\n")
	b.WriteString("// 策略来源(DDL 注释 DSL,review 时与 schema.sql 直接比对):\n")
	for _, d := range spec.TableDirectives {
		fmt.Fprintf(&b, "//   table %s: [%s]\n", spec.Name, d)
	}
	for _, c := range spec.Columns {
		if len(c.Directives) == 0 {
			continue
		}
		fmt.Fprintf(&b, "//   column %s.%s: [%s]\n", spec.Name, c.Physical, strings.Join(c.Directives, " "))
	}
	b.WriteString("//\n")
	b.WriteString("// 逻辑键(camelCase)是对外契约;snake_case 物理列名仅在本文件内部使用。\n")
	b.WriteString("package " + tc.opts.Package + "\n\n")
	b.WriteString(tc.importsSection())
	return b.String()
}

func (tc *tableCode) importsSection() string {
	needTime := false
	for _, c := range tc.spec.Columns {
		if strings.Contains(c.GoType, "time.Time") {
			needTime = true
		}
	}
	var std, rest []string
	std = append(std, `"context"`)
	if needTime {
		std = append(std, `"time"`)
	}
	rest = append(rest, `sq "github.com/Masterminds/squirrel"`, `"github.com/jackc/pgx/v5"`)
	if tc.opts.ModelImport != "" {
		rest = append(rest, fmt.Sprintf("%s %q", tc.opts.ModelPackage, tc.opts.ModelImport))
	}
	rest = append(rest, fmt.Sprintf("dynq %q", tc.opts.RuntimeImport))
	sort.Strings(std)
	sort.Strings(rest)
	var b strings.Builder
	b.WriteString("import (\n")
	for _, l := range std {
		b.WriteString("\t" + l + "\n")
	}
	b.WriteString("\n")
	for _, l := range rest {
		b.WriteString("\t" + l + "\n")
	}
	b.WriteString(")\n\n")
	return b.String()
}

