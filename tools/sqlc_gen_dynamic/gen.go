var dataTypeConst = map[string]string{
	"integer": "dynq.DataTypeInteger", "number": "dynq.DataTypeNumber",
	"datetime": "dynq.DataTypeDatetime", "date": "dynq.DataTypeDate",
	"string": "dynq.DataTypeString", "boolean": "dynq.DataTypeBoolean",
	"uuid": "dynq.DataTypeUUID", "enum": "dynq.DataTypeEnum",
	"jsonb": "dynq.DataTypeJSONB", "int_array": "dynq.DataTypeIntArray",
}

var opConst = map[string]string{
	"eq": "dynq.OpEq", "neq": "dynq.OpNeq", "gt": "dynq.OpGt", "gte": "dynq.OpGte",
	"lt": "dynq.OpLt", "lte": "dynq.OpLte", "between": "dynq.OpBetween",
	"in": "dynq.OpIn", "not_in": "dynq.OpNotIn", "prefix": "dynq.OpPrefix",
	"suffix": "dynq.OpSuffix", "contains": "dynq.OpContains",
	"is_null": "dynq.OpIsNull", "not_null": "dynq.OpNotNull", "has": "dynq.OpHas",
}

func (tc *tableCode) registrySection() string {
	spec := tc.spec
	var b strings.Builder
	fmt.Fprintf(&b, "// %sRegistry 是本表的生成期元数据:协议校验白名单、typed 查询参数与前端\n", lowerFirst(spec.Singular))
	b.WriteString("// schema 均由该元数据生成,三者由构造保证一致。运行期能力为 registry 能力\n")
	b.WriteString("// 减去 opts 禁用项(纯减法,只能禁用不能开启)。\n")
	fmt.Fprintf(&b, "var %sRegistry = dynq.TableMeta{\n", tc.reg)
	fmt.Fprintf(&b, "\tResource: %q,\n", spec.Resource)
	fmt.Fprintf(&b, "\tTable:    %q,\n", tableNameQualified(spec.Name, tc.opts))
	b.WriteString("\tFields: []dynq.FieldMeta{\n")
	for _, c := range spec.Columns {
		b.WriteString("\t\t{\n")
		fmt.Fprintf(&b, "\t\t\tKey:        %q,\n", c.Key)
		fmt.Fprintf(&b, "\t\t\tColumn:     %q,\n", c.Physical)
		fmt.Fprintf(&b, "\t\t\tLabel:      %q,\n", c.Label)
		fmt.Fprintf(&b, "\t\t\tDataType:   %s,\n", dataTypeOrRaw(c.DataType))
		fmt.Fprintf(&b, "\t\t\tNullable:   %v,\n", c.Nullable)
		if len(c.Ops) > 0 {
			ops := make([]string, len(c.Ops))
			for i, op := range c.Ops {
				ops[i] = opConst[op]
			}
			fmt.Fprintf(&b, "\t\t\tOps:        []dynq.Op{%s},\n", strings.Join(ops, ", "))
		}
		fmt.Fprintf(&b, "\t\t\tSortable:   %v,\n", c.Sortable)
		fmt.Fprintf(&b, "\t\t\tSelectable: %v,\n", c.Selectable)
		fmt.Fprintf(&b, "\t\t\tHidden:     %v,\n", c.Hidden)
		if len(c.EnumVals) > 0 {
			quoted := make([]string, len(c.EnumVals))
			for i, v := range c.EnumVals {
				quoted[i] = strconv.Quote(v)
			}
			fmt.Fprintf(&b, "\t\t\tEnum:       []string{%s},\n", strings.Join(quoted, ", "))
		}
		if c.Cast() != "" {
			fmt.Fprintf(&b, "\t\t\tCast:       %q,\n", c.Cast())
		}
		if c.API != nil {
			b.WriteString("\t\t\tAPI: &dynq.FieldAPI{\n")
			fmt.Fprintf(&b, "\t\t\t\tEndpoint: %q,\n", c.API.Endpoint)
			fmt.Fprintf(&b, "\t\t\t\tValueKey: %q,\n", c.API.ValueKey)
			fmt.Fprintf(&b, "\t\t\t\tLabelKey: %q,\n", c.API.LabelKey)
			fmt.Fprintf(&b, "\t\t\t\tMode:     %q,\n", c.API.Mode)
			b.WriteString("\t\t\t},\n")
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t},\n")
	if len(spec.DefaultSort) > 0 {
		b.WriteString("\tDefaultSort: []dynq.OrderBy{\n")
		for _, ds := range spec.DefaultSort {
			fmt.Fprintf(&b, "\t\t{Field: %q, Desc: %v},\n", camelKey(ds.Column), ds.Desc)
		}
		b.WriteString("\t},\n")
	}
	fmt.Fprintf(&b, "\tTiebreaker:  %q,\n", spec.Tiebreaker)
	fmt.Fprintf(&b, "\tPageDefault: %d,\n", spec.PageDefault)
	fmt.Fprintf(&b, "\tPageMax:     %d,\n", spec.PageMax)
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// %sFieldIndex 是逻辑字段名到 registry 字段下标的映射,供白名单校验使用。\n", tc.reg)
	fmt.Fprintf(&b, "var %sFieldIndex = map[dynq.FieldName]int{\n", tc.reg)
	for i, c := range spec.Columns {
		fmt.Fprintf(&b, "\t%q: %d,\n", c.Key, i)
	}
	b.WriteString("}\n")

	for _, c := range spec.Columns {
		if len(c.EnumVals) == 0 || len(c.Ops) == 0 {
			continue
		}
		quoted := make([]string, len(c.EnumVals))
		for i, v := range c.EnumVals {
			quoted[i] = strconv.Quote(v)
		}
		fmt.Fprintf(&b, "\n// %s%sEnumVals 是 %s 字段的合法枚举值白名单,供类型收敛校验使用。\n", tc.reg, c.GoConst, c.Key)
		fmt.Fprintf(&b, "var %s%sEnumVals = []string{%s}\n", tc.reg, c.GoConst, strings.Join(quoted, ", "))
	}
	return b.String()
}

func dataTypeOrRaw(dt string) string {
	if c, ok := dataTypeConst[dt]; ok {
		return c
	}
	return strconv.Quote(dt)
}

func (tc *tableCode) fieldConstSection() string {
	spec := tc.spec
	var b strings.Builder
	fmt.Fprintf(&b, "// %sField 提供逻辑字段常量,供禁用选项、OrderBy 与 SelectFields 引用。\n", spec.Singular)
	b.WriteString("// 字段名拼写错误将在编译期被捕获;@hidden 列不提供常量。\n")
	fmt.Fprintf(&b, "var %sField = struct {\n", spec.Singular)
	for _, c := range spec.Columns {
		if c.Hidden {
			continue
		}
		fmt.Fprintf(&b, "\t%s dynq.FieldName\n", c.GoConst)
	}
	b.WriteString("}{\n")
	for _, c := range spec.Columns {
		if c.Hidden {
			continue
		}
		fmt.Fprintf(&b, "\t%s: %q,\n", c.GoConst, c.Key)
	}
	b.WriteString("}\n")
	return b.String()
}

// ---- Params ----

// opSuffix:op → Params 字段后缀与目标槽位后缀。
var opSuffix = map[string]string{
	"eq": "", "neq": "Neq", "in": "In", "not_in": "NotIn",
	"gt": "Gt", "gte": "Gte", "lt": "Lt", "lte": "Lte",
	"contains": "Contains", "prefix": "Prefix", "suffix": "Suffix",
	"is_null": "IsNull", "not_null": "NotNull", "has": "Has",
}

func (tc *tableCode) paramsSection() string {
	spec := tc.spec
	var b strings.Builder
	fmt.Fprintf(&b, "// List%sParams 是 typed 门的查询参数,供内部调用方直接构造(编译期安全)。\n", tc.res)
	b.WriteString("// 每个字段以单值承载一个操作符,因此无法表达协议门可拒绝的条件冲突——\n")
	b.WriteString("// 冲突检测仅在协议门执行。\n")
	b.WriteString("//\n")
	b.WriteString("// 各操作符字段的零值语义:\n")
	b.WriteString("//   - 指针/切片字段为 nil 或空时,该条件不参与过滤;\n")
	b.WriteString("//   - 模糊匹配字段为零值 \"\" 时,该条件不参与过滤;\n")
	b.WriteString("//   - IsNull/NotNull 为 false 时不参与,二者同时为 true 非法。\n")
	fmt.Fprintf(&b, "type List%sParams struct {\n", tc.res)
	for _, c := range spec.Columns {
		if c.Hidden {
			continue
		}
		seen := map[string]bool{}
		emit := func(name, typ string) {
			if seen[name] {
				return // between 拆分与独立 gte/lte 共享目标字段,去重
			}
			seen[name] = true
			fmt.Fprintf(&b, "\t%s %s\n", name, typ)
		}
		sliceType := "[]" + c.GoType
		if strings.HasPrefix(c.GoType, "[]") {
			sliceType = c.GoType // int_array 列的 GoType 已是切片,不再包一层
		}
		for _, op := range orderedOps(c.Ops) {
			switch op {
			case "between":
				emit(fmt.Sprintf("%sGte", c.GoConst), "*"+c.GoType)
				emit(fmt.Sprintf("%sLte", c.GoConst), "*"+c.GoType)
			case "eq":
				emit(c.GoConst, "*"+c.GoType)
			case "neq", "gt", "gte", "lt", "lte":
				emit(fmt.Sprintf("%s%s", c.GoConst, opSuffix[op]), "*"+c.GoType)
			case "in", "not_in":
				emit(fmt.Sprintf("%s%s", c.GoConst, opSuffix[op]), sliceType)
			case "contains", "prefix", "suffix":
				emit(fmt.Sprintf("%s%s", c.GoConst, opSuffix[op]), "string")
			case "is_null", "not_null":
				emit(fmt.Sprintf("%s%s", c.GoConst, opSuffix[op]), "bool")
			case "has":
				emit(fmt.Sprintf("%sHas", c.GoConst), c.GoType)
			}
		}
	}
	b.WriteString("\t// OrderBy 指定排序(逻辑字段名与方向);为 nil 时回落表级 @default_sort。\n")
	b.WriteString("\tOrderBy []dynq.OrderBy\n")
	b.WriteString("\t// SelectFields 指定动态投影列(逻辑键);为 nil 时默认全量投影(除 @hidden 列)。\n")
	b.WriteString("\tSelectFields []dynq.FieldName\n")
	b.WriteString("\t// Limit 为 offset 模式的每页条数,为 0 时使用表级默认 pageSize。\n")
	b.WriteString("\tLimit  uint32\n")
	b.WriteString("\t// Offset 为 offset 模式的偏移量,仅在 offset 模式生效。\n")
	b.WriteString("\tOffset uint32\n")
	b.WriteString("\t// After 为游标模式的不透明续翻凭证;为 nil 时使用 offset 模式,与 Offset>0 互斥。\n")
	b.WriteString("\tAfter *string\n")
	b.WriteString("}\n")
	return b.String()
}

// orderedOps 按 canonical 顺序返回 ops。
func orderedOps(ops []string) []string {
	canonical := []string{"eq", "neq", "in", "not_in", "gt", "gte", "lt", "lte", "between", "contains", "prefix", "suffix", "is_null", "not_null", "has"}
	var out []string
	for _, c := range canonical {
		for _, op := range ops {
			if op == c {
				out = append(out, op)
				break
			}
		}
	}
	return out
}

// coerceCall 返回标量收敛表达式(不含错误处理)。
func (tc *tableCode) coerceCall(c *ColumnSpec, valueExpr string, right bool) (call string, resultVar string) {
	src := "c.Value"
	if right {
		src = "c.RightValue"
	}
	_ = valueExpr
	switch c.DataType {
	case "integer":
		return "dynq.AsInt64(" + src + ")", "v"
	case "number":
		return "dynq.AsFloat64(" + src + ")", "v"
	case "datetime":
		return "dynq.AsTime(" + src + ")", "v"
	case "date":
		return "dynq.AsDate(" + src + ")", "v"
	case "string":
		return "dynq.AsString(" + src + ")", "v"
	case "boolean":
		return "dynq.AsBool(" + src + ")", "v"
	case "uuid":
		return "dynq.AsUUID(" + src + ")", "v"
	case "enum":
		return "dynq.AsEnum(" + tc.reg + c.GoConst + "EnumVals, " + src + ")", "v"
	case "jsonb":
		return "dynq.AsJSON(" + src + ")", "v"
	case "int_array":
		return "dynq.AsInt64Slice(" + src + ")", "vs"
	default: // unmapped:仅可 is_null/not_null,无标量收敛
		return "", ""
	}
}

func (tc *tableCode) coerceSliceCall(c *ColumnSpec) string {
	switch c.DataType {
	case "integer", "int_array":
		return "dynq.AsInt64Slice(c.Value)"
	case "number":
		return "dynq.AsFloat64Slice(c.Value)"
	case "datetime":
		return "dynq.AsTimeSlice(c.Value)"
	case "date":
		return "dynq.AsDateSlice(c.Value)"
	case "string":
		return "dynq.AsStringSlice(c.Value)"
	case "boolean":
		return "dynq.AsBoolSlice(c.Value)"
	case "uuid":
		return "dynq.AsUUIDSlice(c.Value)"
	case "enum":
		return "dynq.AsEnumSlice(" + tc.reg + c.GoConst + "EnumVals, c.Value)"
	default:
		return ""
	}
}

// takeLine 生成槽位占用语句。
func takeLine(c *ColumnSpec, slot string) string {
	return fmt.Sprintf("if err := slots.Take(%q, i, %q); err != nil {\n\t\t\t\t\treturn out, err\n\t\t\t\t}", c.Key+"."+slot, c.Key)
}

func coerceErrLine(c *ColumnSpec) string {
	return fmt.Sprintf("if cerr != nil {\n\t\t\t\t\treturn out, dynq.AsError(cerr).At(dynq.KindWhere, i, %q)\n\t\t\t\t}", c.Key)
}

// parseOpCase 生成单个 (字段, op) 的 case 体。
func (tc *tableCode) parseOpCase(c *ColumnSpec, op string) string {
	var b strings.Builder
	fmt.Fprintf(&b, "\t\t\tcase %s:\n", opConst[op])
	body := tc.parseOpBody(c, op)
	for _, line := range strings.Split(strings.TrimRight(body, "\n"), "\n") {
		b.WriteString("\t\t\t\t" + line + "\n")
	}
	return b.String()
}

func (tc *tableCode) parseOpBody(c *ColumnSpec, op string) string {
	var b strings.Builder
	slot := func(s string) { b.WriteString(takeLine(c, s) + "\n") }
	coerce := func(right bool) string {
		call, varName := tc.coerceCall(c, "", right)
		fmt.Fprintf(&b, "%s, cerr := %s\n", varName, call)
		b.WriteString(coerceErrLine(c) + "\n")
		return varName
	}
	switch op {
	case "eq", "neq":
		slot(op)
		v := coerce(false)
		if c.DataType == "enum" {
			fmt.Fprintf(&b, "out.%s%s = dynq.Addr(%s(%s))\n", c.GoConst, opSuffix[op], c.EnumGoType, v)
		} else {
			fmt.Fprintf(&b, "out.%s%s = &%s\n", c.GoConst, opSuffix[op], v)
		}
	case "in", "not_in":
		slot(op)
		fmt.Fprintf(&b, "vs, cerr := %s\n", tc.coerceSliceCall(c))
		b.WriteString(coerceErrLine(c) + "\n")
		b.WriteString("if err := budget.Add(len(vs)); err != nil {\n\t\t\t\t\treturn out, dynq.AsError(err).At(dynq.KindWhere, i, \"" + c.Key + "\")\n\t\t\t}\n")
		if c.DataType == "enum" {
			fmt.Fprintf(&b, "out.%s%s = dynq.ConvertSlice[%s](vs)\n", c.GoConst, opSuffix[op], c.EnumGoType)
		} else {
			fmt.Fprintf(&b, "out.%s%s = vs\n", c.GoConst, opSuffix[op])
		}
	case "gt", "gte", "lt", "lte":
		slot(op)
		v := coerce(false)
		fmt.Fprintf(&b, "out.%s%s = &%s\n", c.GoConst, opSuffix[op], v)
	case "between":
		slot("gte")
		slot("lte")
		lv := func() string {
			call, _ := tc.coerceCall(c, "", false)
			b.WriteString("lv, cerr := " + call + "\n")
			b.WriteString(coerceErrLine(c) + "\n")
			return "lv"
		}()
		rv := func() string {
			call, _ := tc.coerceCall(c, "", true)
			b.WriteString("rv, cerr := " + call + "\n")
			b.WriteString(coerceErrLine(c) + "\n")
			return "rv"
		}()
		fmt.Fprintf(&b, "out.%sGte = &%s\nout.%sLte = &%s\n", c.GoConst, lv, c.GoConst, rv)
	case "contains", "prefix", "suffix":
		slot(op)
		v := coerce(false)
		fmt.Fprintf(&b, "out.%s%s = %s\n", c.GoConst, opSuffix[op], v)
	case "is_null", "not_null":
		slot(op)
		fmt.Fprintf(&b, "out.%s%s = true\n", c.GoConst, opSuffix[op])
	case "has":
		slot(op)
		v := coerce(false)
		fmt.Fprintf(&b, "out.%sHas = %s\n", c.GoConst, v)
	}
	return b.String()
}

func lowerFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

func tableNameQualified(name string, opts *Options) string {
	if opts.Schema != "" && opts.Schema != "public" {
		return opts.Schema + "." + name
	}
	return name
}
